/**
 * Extensions `ingest` knows how to read, mirroring the CLI's own list. Anything
 * else earns a 415 with this list in the message, which is far kinder than an
 * ingest failure two seconds into a background job.
 */
export const UPLOAD_EXTENSIONS = [
  '.md',
  '.markdown',
  '.txt',
  '.text',
  '.pdf',
  '.docx',
  '.html',
  '.htm',
  '.rtf',
  '.json',
  '.adoc',
  '.rst',
] as const;

/** 32 MB. Comfortably above any explainer source, well below trouble. */
export const MAX_UPLOAD_BYTES = 32 * 1024 * 1024;

/**
 * Reduce a client-supplied filename to something safe to create.
 *
 * Drops any directory part, then sanitises the stem and the extension
 * separately: the extension has to survive intact because `ingest` dispatches on
 * it, while the stem is only a label and can be scrubbed freely. Runs of
 * disallowed characters collapse to a single `-`, and leading/trailing
 * separators are trimmed so `"../../evil name!.md"` becomes `evil-name.md`
 * rather than `evil-name-.md`.
 */
export function safeUploadName(name: string): string {
  const base = name.split(/[\\/]/).pop() ?? '';
  const ext = uploadExtension(base);
  const stem = (ext === '' ? base : base.slice(0, -ext.length))
    .replace(/[^A-Za-z0-9._-]+/g, '-')
    .replace(/^[.\-]+/, '')
    .replace(/[.\-]+$/, '')
    .slice(0, 100);
  // An empty stem means the name was entirely punctuation (or was just an
  // extension, like ".gitignore"). Give it a neutral one.
  if (stem === '') return `upload${ext === '' ? '.txt' : ext}`;
  return `${stem}${ext}`;
}

export function uploadExtension(name: string): string {
  const match = /\.[A-Za-z0-9]+$/.exec(name);
  return match ? match[0].toLowerCase() : '';
}
