/**
 * Request schemas for the studio API.
 *
 * These are written out longhand rather than derived from `StoryboardMeta` in
 * `@inkcast/core`, for two reasons. The mechanical one: deriving them would
 * require a *value* import of core, and `lib/store.ts` explains why routes only
 * ever import core types. The better one: an API boundary should state what it
 * accepts. `meta` here is a patch of user-supplied overrides with bounds that
 * make sense over HTTP (an fps of 10000 is a denial-of-service, not a
 * preference), which is a different thing from the IR's own defaults.
 *
 * If a new field lands in `StoryboardMeta`, add it here too — it is the only
 * place the two can drift.
 */

import { z } from 'zod';

/** Mirrors `StoryboardMeta` in packages/core/src/storyboard.ts, all optional. */
export const MetaPatch = z
  .object({
    language: z.string().trim().min(1).max(32).optional(),
    aspect: z.enum(['16:9', '9:16', '1:1']).optional(),
    palette: z.enum(['mono', 'color']).optional(),
    fps: z.number().int().min(1).max(60).optional(),
    /**
     * A style pack id (plan 7.3). Bounded rather than enumerated: the list of styles is a
     * directory on the server (`styles/`), and `parseStoryboard` in `@inkcast/core` is
     * what rejects a name no pack claims — with a message naming the ones that exist.
     * Enumerating four here would reject a fifth pack at the edge, before the one check
     * that can explain itself ever ran.
     */
    style: z
      .string()
      .trim()
      .min(1)
      .max(40)
      .regex(/^[a-z0-9][a-z0-9-]*$/)
      .optional(),
    voice: z.string().trim().min(1).max(120).optional(),
    outroSec: z.number().min(0).max(30).optional(),
  })
  .strict();

export type MetaPatch = z.infer<typeof MetaPatch>;

/** The `meta` field names, for readers that have to pull them out of a form. */
export const META_KEYS = Object.keys(MetaPatch.shape) as (keyof MetaPatch)[];

/** The two `meta` fields that arrive as numbers rather than strings. */
export const NUMERIC_META_KEYS = [
  'fps',
  'outroSec',
] as const satisfies readonly (keyof MetaPatch)[];

/**
 * Project ids are generated by `projectId()` in core — base36 timestamps or hex
 * digests. Constraining the alphabet here is the first of two path-traversal
 * defences; `projectDir()` in the store is the second.
 */
export const ProjectId = z
  .string()
  .regex(/^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/, 'not a valid project id');

/**
 * Source text. The floor is a real constraint, not decoration: the planner
 * needs enough material to find structure, and "hi" produces a one-scene video
 * that looks like a bug. The ceiling keeps a runaway paste out of the planner.
 */
const SourceText = z.string().trim().min(20, 'needs at least 20 characters of text').max(500_000);

const SourceUrl = z
  .string()
  .trim()
  .url('must be a valid URL')
  .refine(
    (value) => {
      try {
        return ['http:', 'https:'].includes(new URL(value).protocol);
      } catch {
        return false;
      }
    },
    { message: 'only http and https URLs can be fetched' },
  );

/**
 * The generate request, minus the "exactly one source" rule.
 *
 * That rule lives in the route rather than in a `.refine()` here because a
 * multipart upload is a fourth source that never appears in these fields — the
 * route is the only place that can see all four at once, so it is the only place
 * the rule can be stated once instead of twice.
 */
export const GenerateFields = z
  .object({
    text: SourceText.optional(),
    url: SourceUrl.optional(),
    /**
     * A path on the *server*, for casting something already in the repo such as
     * `examples/gradient-descent.md`. The route confines it to the repo root —
     * the studio is local, but "local" is not a reason to expose `/etc/passwd`
     * to a stray fetch. Browser uploads use multipart instead.
     */
    filePath: z.string().trim().min(1).max(1024).optional(),
    title: z.string().trim().min(1).max(200).optional(),
    /** Reuse a project directory: resumes cached stages instead of starting over. */
    projectId: ProjectId.optional(),
    /** Redo every stage even when the cache says it is fresh. */
    force: z.boolean().optional(),

    /**
     * The shape of the film: how long, and how the board behaves between beats.
     *
     * Two values, and deliberately not the five `PresetName` has. `standard`,
     * `short` and `square` all accumulate onto one mega-canvas — the defect class
     * `docs/PLAN-WATCHABILITY.md` §E2 measures — and the studio must not be able to
     * ask for it. `standard` in particular is what every pinned hash and every
     * cached project on disk is compiled against, so it stays reachable from the CLI
     * and is not a thing a form can select.
     *
     * `.strict()` extended deliberately. Until now the schema's own note said a
     * hosted visitor "cannot ask for `standard` and cannot override this by sending
     * one — the field is refused at the schema" — which was true and was also why
     * the *local* studio could not reach `explainer` at all, and cast at the
     * mega-canvas default every time. The refusal survives where it was pointed:
     * neither value here is `standard`, and hosted still pins its own server-side.
     */
    preset: z.enum(['explainer', 'deepdive']).optional(),

    /**
     * Storyboard overrides, accepted **either** nested under `meta` or flattened
     * at the top level (`{ aspect: '9:16', voice: 'af_heart' }`).
     *
     * Both spellings exist because both are natural: nesting mirrors the IR, and
     * flattening is what an HTML form produces. Supporting the pair costs one
     * merge in `mergeMeta` and removes a whole category of "why is my aspect
     * ratio being ignored" bug. The shape is spread from `MetaPatch` so the two
     * can never list different fields.
     */
    meta: MetaPatch.optional(),
    ...MetaPatch.shape,
  })
  .strict();

export type GenerateFields = z.infer<typeof GenerateFields>;

/**
 * Collapse the flattened and nested forms into one patch.
 * An explicit `meta` wins over a top-level field of the same name.
 */
export function mergeMeta(fields: GenerateFields): MetaPatch | undefined {
  const merged: Record<string, unknown> = {};
  for (const key of META_KEYS) {
    if (fields[key] !== undefined) merged[key] = fields[key];
  }
  Object.assign(merged, stripUndefined(fields.meta ?? {}));
  return Object.keys(merged).length === 0 ? undefined : (merged as MetaPatch);
}

function stripUndefined(input: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.entries(input).filter(([, v]) => v !== undefined));
}

export const EditBody = z
  .object({
    instruction: z
      .string()
      .trim()
      .min(3, 'an instruction needs at least a few characters')
      .max(2000),
  })
  .strict();

export const RerenderBody = z
  .object({
    /** Default true — asking to re-render means asking for a new video. */
    force: z.boolean().optional(),
  })
  .strict();

/**
 * `POST /api/projects/<id>/share` — publish or unpublish one project.
 *
 * `shared` defaults to **true** because the overwhelmingly common call is a
 * Share button with no body at all, and `parseJsonBody` already treats an empty
 * body as `{}`. Unpublishing is the deliberate act here (`{"shared":false}`),
 * which inverts the default in `ProjectRecordSchema` — and it should: the
 * dangerous direction is the one that makes a film public, and that direction is
 * the one that requires an explicit request to this route.
 *
 * One field rather than a `PUT` of the whole record: sharing is the only piece
 * of project metadata a client is allowed to set directly, and a schema that
 * accepted more would be a schema someone eventually used to rewrite a title or
 * a cost. `.strict()` makes that refusal explicit rather than silent.
 */
export const ShareBody = z
  .object({
    shared: z.boolean().default(true),
  })
  .strict();

