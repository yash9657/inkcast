import { cn, randomFromSeed, seedFrom } from '@/lib/utils';
import { inkStrokePath } from '@/components/ui/ink';

/**
 * The mark, the wordmark, and the geometry both are cut from.
 *
 * ## What the mark is
 *
 * A square ink-bordered tile — the whiteboard — with one confident marker stroke
 * rising left-to-right across it, ending in a solid triangular nib. The nib is
 * doing two jobs at once and that is the whole idea: it is the chisel tip of the
 * pen that drew the stroke, and it is a play triangle, because the artefact this
 * product makes is a video of that board being drawn. "cast" is the stroke.
 *
 * The tile is not filled with the accent. An accent-filled square is what the
 * old mark was (`bg-primary` tile, white glyph inside) and it lost the one thing
 * this brand actually owns: the board is paper, the ink is dark, and the marker
 * is the only saturated thing in the frame. That is true of every rendered frame
 * the pipeline produces, so it should be true of the mark. The offset accent
 * shadow under the tile is `--elevation-pop` at mark scale (4 units of 32, i.e.
 * `4px 4px 0` when the mark is drawn at 32px) — the same hard, zero-blur
 * elevation the rest of the system uses, drawn inside the SVG rather than as a
 * `box-shadow` so that one file is the whole mark and the favicon, the OG image
 * and the video brand plate can all be cut from it without a CSS context.
 *
 * ## Why the numbers live here as constants
 *
 * `MARK` is exported because three other things need this exact geometry and
 * none of them can render this component: `app/icon.svg` and the raster icons
 * (generated by `assets/brand/make-brand-assets.mjs`), and the video brand plate
 * in `packages/render`, which draws a small logo into the last 1.2 s of every
 * film from a vector spec. `assets/brand/geometry.json` is the record of these
 * numbers across that package boundary — a JSON file in the repo root is the
 * only form all three consumers can read — and the generator script asserts
 * that the path strings below still match it, so the two cannot drift silently.
 * If you change a number here, run the generator; it will fail loudly if you
 * changed only one of the two.
 *
 * ## Why it survives 16px
 *
 * Verified by rasterising, not by hoping (plan item C4). Three findings from the
 * 16px renders, each of which shaped a number above:
 *
 *   1. `shape-rendering: crispEdges` on the two rectangles is the difference
 *      between a black frame and a grey smudge at 16px, because a 2-unit border
 *      in a 32-unit box lands on 0.94 device pixels and antialiases to 50% grey.
 *      It is set on the icon assets only. In the UI the mark is drawn at 24–32px
 *      on displays that are usually 2×, where snapping a 1.75px border to whole
 *      device pixels makes opposite sides of the tile visibly different weights;
 *      antialiasing is the better trade there. Same geometry, different hint.
 *   2. The offset shadow is dropped from the favicon (`icon.svg` crops to
 *      `MARK.viewBoxCropped`, which is the tile's own bounds). Keeping it costs
 *      4 of 32 units to a decoration nobody can resolve at 16px and shrinks the
 *      tile — and therefore the stroke — by a quarter.
 *   3. The nib does not survive as a resolvable triangle at 16px; it reads as a
 *      thickening at the top right. That is accepted. What has to survive at
 *      16px is "bordered square, one rising violet stroke", and that does.
 */
export const MARK = {
  /** The full mark, shadow included. */
  viewBox: '0 0 32 32',
  /**
   * The tile alone, for contexts that cannot afford the shadow (favicon) or that
   * paint their own elevation. 0.4 units of bleed on each side so the 2-unit
   * border is not clipped by a rasteriser rounding outward.
   */
  viewBoxCropped: '0.4 0.4 27.2 27.2',
  /** The offset accent block behind the tile. Outer tile box translated (4, 4). */
  shadow: { x: 5, y: 5, size: 26 },
  /** Stroke-centred rect: outer box 1→27, inner (paper) box 3→25. */
  tile: { x: 2, y: 2, size: 24, strokeWidth: 2 },
  /**
   * The cast. A quadratic that leaves the bottom-left inner corner at 59° and
   * flattens to 34° as it arrives at the nib — a stroke drawn with a wrist,
   * which is what makes it read as a marker rather than an arrow from an icon
   * set. It ends *inside* the nib triangle, 2.2 units past its base edge, which
   * is more than the 1.65-unit cap radius, so the round cap is fully overpainted
   * and the join has no notch. An earlier version ended on the base edge and the
   * cap poked out below it as a hook.
   */
  strokePath: 'M6.2 22.9Q9.6 17.2 19.4 10.7',
  strokeWidth: 3.3,
  /**
   * The nib: apex right, base edge 9.6 units long and tilted 10° off vertical,
   * so the triangle's own axis sits ~5° above the horizontal. Nearly upright is
   * what makes it read as a play button; the stroke arriving at 34° into it is
   * what makes the same shape read as a chisel tip held at an angle.
   *
   * The base is 2.9× the stroke's width, and that ratio is the whole difference
   * between a play button and an arrowhead. `packages/render/src/sketch.ts`
   * found the same thing independently while building the video brand plate
   * (`BRAND_MARK.nibHalfWidth`): at 1.4× the base corners sit barely wider than
   * the shaft running into them and the mark reads as an arrow, barbs and all.
   * The first version of this mark was at 2.26× and still read arrow-ish at
   * 512px; widening the base while thinning the stroke fixed it without costing
   * anything at 16px, where a fifth of a pixel of stroke is invisible anyway.
   */
  nibPath: 'M24.3 10.5 18.05 15.83 16.35 6.37Z',
} as const;

/** Ratios that hold the lockup together at any size. See `Logo`. */
const LOCKUP = {
  /** Wordmark font size as a fraction of the mark's edge. */
  fontScale: 0.68,
  /** Gap between mark and wordmark, as a fraction of the mark's edge. */
  gapScale: 0.3,
  /** Highlighter stroke weight in CSS px, as a fraction of the mark's edge. */
  strokeScale: 0.085,
};

/**
 * The mark. `size` is the edge of the square in px, shadow included.
 *
 * Every colour is a token utility, so the mark inverts with the theme without a
 * `dark:` variant anywhere: `border` is ink on paper and paper on ink, `card` is
 * the tile's own surface in both, and `primary` is cast violet, lifted in dark
 * mode by the token layer. The tile is filled rather than transparent because a
 * hard offset shadow only reads as elevation if the thing casting it is opaque.
 */
export function LogoMark({ size = 28, className }: { size?: number; className?: string }) {
  return (
    <svg
      viewBox={MARK.viewBox}
      width={size}
      height={size}
      className={cn('shrink-0', className)}
      aria-hidden
      focusable="false"
    >
      <rect
        x={MARK.shadow.x}
        y={MARK.shadow.y}
        width={MARK.shadow.size}
        height={MARK.shadow.size}
        className="fill-primary"
      />
      <rect
        x={MARK.tile.x}
        y={MARK.tile.y}
        width={MARK.tile.size}
        height={MARK.tile.size}
        strokeWidth={MARK.tile.strokeWidth}
        className="fill-card stroke-border"
      />
      <path
        d={MARK.strokePath}
        fill="none"
        strokeWidth={MARK.strokeWidth}
        strokeLinecap="round"
        className="stroke-primary"
      />
      <path d={MARK.nibPath} className="fill-primary" />
    </svg>
  );
}

/**
 * The wordmark's flourish: a Shantell-shaped hand stroke under the `k`.
 *
 * Generated from `inkStrokePath` with a fixed seed rather than drawn by hand, so
 * it is the same wobble the board's own `InkUnderline` produces — the chrome
 * quoting the artefact, which is the only justification this system accepts for
 * a hand-drawn line in a UI. Fixed seed also means server and client render byte
 * -identical markup; a re-roll per render would be a hydration mismatch. It is
 * imported from `components/ui/ink` directly rather than from the
 * `@/components/ui` barrel so that drawing a logo in the app shell does not pull
 * all 25 primitives into that route's module graph for one pure function.
 *
 * It over- and undershoots the letter (x from −7 to 107 in a 100-wide viewBox,
 * with `overflow-visible`) because a highlighter stroke that stops exactly at
 * the glyph's edges reads as a rule, not as a hand. `non-scaling-stroke` keeps
 * the weight in CSS px so the stroke does not turn into a hairline when the
 * lockup is small or a slab when it is large.
 */
function KStroke({ weight }: { weight: number }) {
  const rand = randomFromSeed(seedFrom('inkcast-wordmark-k'));
  const d = inkStrokePath(rand, { x: -7, y: 6.2 }, { x: 107, y: 5.4 }, { amplitude: 1.6 });

  return (
    <svg
      aria-hidden
      focusable="false"
      viewBox="0 0 100 12"
      preserveAspectRatio="none"
      className="pointer-events-none absolute -bottom-[0.1em] left-0 h-[0.3em] w-full overflow-visible stroke-highlighter"
    >
      <path
        d={d}
        fill="none"
        strokeWidth={weight}
        strokeLinecap="round"
        vectorEffect="non-scaling-stroke"
      />
    </svg>
  );
}

export type LogoVariant = 'lockup' | 'mark';

/**
 * Mark plus wordmark. `href` is deliberately not a prop — the callers (marketing
 * header, footer, app shell) each wrap this in their own `Link` with their own
 * `aria-label`, which is why nothing in here is focusable or announced.
 *
 * ## Why the type is sized in px and not with a `text-*` class
 *
 * A lockup is one object with fixed internal proportions, not a paragraph. Its
 * type has to track the mark's edge — at `size={28}` the wordmark is 19px, at
 * the OG image's `size={120}` it is 82px — and no step of the type scale is the
 * right answer at both. So the three ratios in `LOCKUP` are the design, and the
 * px values fall out of `size`. Colour still comes only from tokens; docs/
 * DESIGN.md §10 forbids raw colours, not a logo's optical sizing.
 *
 * The wordmark is lowercase `inkcast` (PLAN-LAUNCH C4) while prose still says
 * "Inkcast". That is intentional and normal — the lockup is a drawn object, the
 * noun in a sentence is a word. The `k` is a separate inline span only so the
 * flourish can be positioned by layout rather than by a guessed advance width;
 * inline spans introduce no word boundary, so assistive tech still reads one
 * word.
 */
export function Logo({
  variant = 'lockup',
  size = 28,
  className,
}: {
  variant?: LogoVariant;
  size?: number;
  className?: string;
}) {
  if (variant === 'mark') return <LogoMark size={size} className={className} />;

  return (
    <span
      className={cn('inline-flex items-center', className)}
      style={{ gap: `${Math.round(size * LOCKUP.gapScale)}px` }}
    >
      <LogoMark size={size} />
      <span
        className="font-display leading-none font-bold text-foreground"
        style={{ fontSize: `${Math.round(size * LOCKUP.fontScale)}px`, letterSpacing: '-0.03em' }}
      >
        in
        <span className="relative inline-block">
          k
          <KStroke weight={Math.max(1.5, size * LOCKUP.strokeScale)} />
        </span>
        cast
      </span>
    </span>
  );
}
